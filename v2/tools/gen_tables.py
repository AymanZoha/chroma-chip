def encode(text, width=18):
    """Host-side helper: text -> list of 6-bit codes, centred in `width` cells."""
    text = text.upper()[:width]
    pad = (width - len(text)) // 2
    text = " " * pad + text + " " * (width - len(text) - pad)
    return [CHARSET.index(c) if c in CHARSET else 0 for c in text]


def write_font():
    assert len(CHARSET) == len(G) == 48
    lines = []
    for code, ch in enumerate(CHARSET):
        rows = G[ch].split()
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
        bits = "".join(rows)
        lines.append(f"      6'd{code:<2}: bits = 35'b{bits};  // '{ch}'")
    v = f"""// Generated by v2/tools/gen_tables.py - do not edit.
// 5x7 font, 48 glyphs. Row 0 is the top row; bit 4 of a row is the leftmost pixel.
`default_nettype none
module font_rom (
    input  wire [5:0] code,
    input  wire [2:0] row,
    output wire [4:0] pixels
);
  reg [34:0] bits;
  always @(*) begin
    case (code)
{chr(10).join(lines)}
      default: bits = 35'd0;
    endcase
  end
  wire [34:0] shifted = bits >> (6'd30 - {{1'b0, row, 2'b00}} - {{3'b000, row}});
  assign pixels = shifted[4:0];
  wire _unused = &{{shifted[34:5], 1'b0}};
endmodule
"""
    open(os.path.join(SRC, "font_rom.v"), "w").write(v)


def write_sin():
    # Quarter-wave table, 65 entries (0..64 of a 256-step circle), Q1.14
    vals = [round(16384 * math.sin(2 * math.pi * i / 256)) for i in range(65)]
    lines = [f"      7'd{i:<2}: q = 15'd{v};" for i, v in enumerate(vals)]
    v = f"""// Generated by v2/tools/gen_tables.py - do not edit.
// sin(2*pi*angle/256) in signed Q1.14, from a 65-entry quarter-wave table.
`default_nettype none
module sin_lut (
    input  wire [7:0]  angle,
    output wire signed [15:0] value
);
  wire [1:0] quad = angle[7:6];
  wire [6:0] idx  = quad[0] ? (7'd64 - {{1'b0, angle[5:0]}}) : {{1'b0, angle[5:0]}};
  reg  [14:0] q;
  always @(*) begin
    case (idx)
{chr(10).join(lines)}
      default: q = 15'd0;
    endcase
  end
  assign value = quad[1] ? -$signed({{1'b0, q}}) : $signed({{1'b0, q}});
endmodule
"""
    open(os.path.join(SRC, "sin_lut.v"), "w").write(v)


if __name__ == "__main__":
    os.makedirs(SRC, exist_ok=True)
    write_font()
    write_sin()
    print("wrote font_rom.v and sin_lut.v")
