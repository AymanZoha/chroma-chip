"""Generate the ROM tables for CHROMA v2: 5x7 font (48 glyphs) and quarter-wave sine.

Writes v2/src/font_rom.v and v2/src/sin_lut.v. Also exports CHARSET for the host side.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")

# 6-bit character codes used on the SPI link. Index = code.
